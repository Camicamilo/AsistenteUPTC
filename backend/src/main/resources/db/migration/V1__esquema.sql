-- Esquema del Asistente Virtual UPTC (compatible con PostgreSQL y con H2 en modo PostgreSQL).
-- Tablas del modelo entidad-relación del documento + las que pidieron las entregas de
-- arquitectura (eventos, auditoría, configuración, disponibilidad).

CREATE TABLE dependencias (
    clave       VARCHAR(30)  PRIMARY KEY,
    nombre      VARCHAR(120) NOT NULL,
    correo      VARCHAR(120),
    telefono    VARCHAR(40),
    enlace      VARCHAR(300),
    horario     VARCHAR(120)
);

-- Solo administradores del panel. Los estudiantes son anónimos (RD-02): se identifican por la sesión.
CREATE TABLE usuarios (
    usuario_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                 VARCHAR(120) NOT NULL,
    correo                 VARCHAR(120) NOT NULL UNIQUE,
    password_hash          VARCHAR(100) NOT NULL,
    rol                    VARCHAR(30)  NOT NULL,
    activo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    debe_cambiar_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_registro         TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_acceso          TIMESTAMP WITH TIME ZONE
);

CREATE TABLE intenciones (
    intent_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_intent  VARCHAR(80)  NOT NULL UNIQUE,
    descripcion    VARCHAR(500),
    categoria      VARCHAR(50)  NOT NULL,
    dependencia    VARCHAR(30)  NOT NULL REFERENCES dependencias (clave),
    social         BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Frases de entrenamiento del motor PLN (la base de datos es la fuente de verdad).
CREATE TABLE ejemplos_intencion (
    ejemplo_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id   BIGINT       NOT NULL REFERENCES intenciones (intent_id) ON DELETE CASCADE,
    texto       VARCHAR(500) NOT NULL
);

CREATE TABLE respuestas (
    respuesta_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id            BIGINT        NOT NULL REFERENCES intenciones (intent_id) ON DELETE CASCADE,
    texto_respuesta      VARCHAR(1500) NOT NULL,
    activa               BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_actualizacion  TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_por      BIGINT REFERENCES usuarios (usuario_id)
);

CREATE TABLE sesiones_chat (
    sesion_id         VARCHAR(100) PRIMARY KEY,
    canal             VARCHAR(30)  NOT NULL,
    fecha_inicio      TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_actividad  TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_fin         TIMESTAMP WITH TIME ZONE,
    causa_cierre      VARCHAR(30),
    total_consultas   INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_sesiones_abiertas ON sesiones_chat (fecha_fin, ultima_actividad);

CREATE TABLE consultas (
    consulta_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id            VARCHAR(100) NOT NULL REFERENCES sesiones_chat (sesion_id),
    texto_original       VARCHAR(500) NOT NULL,
    intent_detectado     VARCHAR(80),
    categoria            VARCHAR(50),
    confianza            NUMERIC(4, 3),
    resuelta             BOOLEAN      NOT NULL,
    motivo_escalamiento  VARCHAR(60),
    respuesta_id         BIGINT,
    tiempo_ms            INT          NOT NULL,
    canal                VARCHAR(30)  NOT NULL,
    fecha_hora           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_consultas_fecha ON consultas (fecha_hora);

CREATE TABLE configuracion (
    id                      INT PRIMARY KEY,
    umbral_confianza        NUMERIC(3, 2) NOT NULL,
    inactividad_sesion_min  INT           NOT NULL,
    plantilla_escalamiento  VARCHAR(500)  NOT NULL,
    notificar_por_correo    BOOLEAN       NOT NULL
);

CREATE TABLE temas_rapidos (
    tema_id   VARCHAR(30)  PRIMARY KEY,
    etiqueta  VARCHAR(60)  NOT NULL,
    consulta  VARCHAR(200) NOT NULL,
    orden     INT          NOT NULL
);

-- Almacén de eventos (EventSourcing, pauta 8.5): solo se insertan filas, nunca se editan.
CREATE TABLE eventos (
    evento_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agregado_id    VARCHAR(100)  NOT NULL,
    tipo_agregado  VARCHAR(30)   NOT NULL,
    version        INT           NOT NULL,
    tipo_evento    VARCHAR(60)   NOT NULL,
    datos          VARCHAR(4000) NOT NULL,
    fecha_hora     TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id     BIGINT,
    CONSTRAINT uq_evento_version UNIQUE (agregado_id, version)
);

CREATE TABLE auditoria (
    auditoria_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario       VARCHAR(120) NOT NULL,
    accion        VARCHAR(80)  NOT NULL,
    detalle       VARCHAR(500)
);
CREATE INDEX idx_auditoria_fecha ON auditoria (fecha);

-- Chequeos de salud cada minuto para medir la disponibilidad real (RNF-02).
CREATE TABLE chequeos_disponibilidad (
    chequeo_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora  TIMESTAMP WITH TIME ZONE NOT NULL,
    pln_ok      BOOLEAN NOT NULL,
    bd_ok       BOOLEAN NOT NULL
);
CREATE INDEX idx_chequeos_fecha ON chequeos_disponibilidad (fecha_hora);
